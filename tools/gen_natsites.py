#!/usr/bin/env python3
"""Makes src/dx/natsites_gen.h: the engine functions the native renderers replace (every install(0x..) of src/dx/natboot.c) and a hash of the first 14 bytes of each in the reference exe.

  python -I tools/gen_natsites.py <reference iw4sp.exe>    write the header
  python -I tools/gen_natsites.py --check                  fail if the list of functions in the header is not the one natboot.c installs (no exe needed: CI)

natboot.c checks this hash before it patches anything: an exe whose timestamp is the reference one but whose bytes at the hook sites differ (a patched or unpacked copy) keeps the game on its own
Direct3D 9 instead of getting hooks written over code the renderer does not know. The header holds a hash, no game bytes.
"""
import os
import re
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "src", "dx", "natboot.c")
OUT = os.path.join(HERE, "..", "src", "dx", "natsites_gen.h")
HEAD = 14  # hook_jump overwrites 14 bytes


def sites():
    text = open(SRC, encoding="utf-8", errors="replace").read()
    out = []
    for m in re.finditer(r"\binstall\((0x[0-9a-fA-F]+),", text):
        v = int(m.group(1), 16)
        if v not in out:
            out.append(v)
    return sorted(out)


def fnv(data, h=0xcbf29ce484222325):
    for b in data:
        h = ((h ^ b) * 0x100000001b3) & 0xFFFFFFFFFFFFFFFF
    return h


def read_heads(exe_path, rvas):
    d = open(exe_path, "rb").read()
    pe = struct.unpack_from("<I", d, 0x3c)[0]
    nsec = struct.unpack_from("<H", d, pe + 6)[0]
    opt = struct.unpack_from("<H", d, pe + 20)[0]
    sec = pe + 24 + opt
    secs = [struct.unpack_from("<8sIIII", d, sec + 40 * i) for i in range(nsec)]
    out = []
    for rva in rvas:
        for _name, vs, va, rs, ro in secs:
            if va <= rva < va + max(vs, rs):
                out.append(d[ro + rva - va: ro + rva - va + HEAD])
                break
        else:
            raise SystemExit("rva 0x%x is in no section" % rva)
    return out


def site_hash(rvas, heads):
    h = 0xcbf29ce484222325
    for rva, head in zip(rvas, heads):
        h = fnv(struct.pack("<I", rva), h)
        h = fnv(head, h)
    return h


def header(rvas, h):
    lines = ["// Generated by tools/gen_natsites.py from src/dx/natboot.c and the reference iw4sp.exe: do not edit.",
             "// The engine functions the native renderers replace, and an FNV-1a 64 hash of their first %d bytes (a hash, no game bytes)." % HEAD,
             "#define NAT_SITE_COUNT %d" % len(rvas),
             "static const unsigned nat_site_rva[NAT_SITE_COUNT] = {"]
    row = []
    for i, r in enumerate(rvas):
        row.append("0x%x" % r)
        if len(row) == 8 or i == len(rvas) - 1:
            lines.append("\t" + ", ".join(row) + ",")
            row = []
    lines += ["};", "#define NAT_SITE_HASH 0x%016xull" % h, ""]
    return "\r\n".join(lines)


def main():
    if len(sys.argv) == 2 and sys.argv[1] == "--check":
        cur = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        have = [int(x, 16) for x in re.findall(r"0x([0-9a-f]+),", cur.split("nat_site_rva")[1].split("};")[0])] if "nat_site_rva" in cur else []
        want = sites()
        if have != want:
            print("src/dx/natsites_gen.h lists %d functions, natboot.c installs %d: run python -I tools/gen_natsites.py <reference iw4sp.exe>" % (len(have), len(want)))
            return 1
        print("natsites_gen.h matches natboot.c (%d functions)" % len(want))
        return 0
    if len(sys.argv) != 2:
        print(__doc__)
        return 2
    rvas = sites()
    heads = read_heads(sys.argv[1], rvas)
    h = site_hash(rvas, heads)
    open(OUT, "w", newline="").write(header(rvas, h))
    print("wrote %s: %d functions, hash 0x%016x" % (OUT, len(rvas), h))
    return 0


sys.exit(main())
